[[nodiscard]] inline bool MatchesKernel(const void* code) {
	return std::memcmp(code, kKernelCode, kKernelCodeSize) == 0;
}

// The kernel's user data: s0 = N, s1 & 0xffff = R, s2 = trailer bytes, s3 = args offset | stride <<
// 16, s[4:7] = args V#, s[8:11] = input V#, s[12:15] = output V#.
struct Params {
	uint32_t n = 0, r = 0, trailer = 0, args_offset = 0, args_stride = 0;
	uint64_t args = 0, input = 0, output = 0;
};

[[nodiscard]] inline uint64_t VBase(const uint32_t* s) {
	return s[0] | (uint64_t {s[1] & 0xffffu} << 32u);
}

[[nodiscard]] inline Params Decode(const uint32_t* s) {
	Params p;
	p.n           = s[0];
	p.r           = s[1] & 0xffffu;
	p.trailer     = s[2];
	p.args_offset = s[3] & 0xffffu;
	p.args_stride = s[3] >> 16u;
	p.args        = VBase(s + 4);
	p.input       = VBase(s + 8);
	p.output      = VBase(s + 12);
	return p;
}

// Plausibility (a bad layout is skipped, never walked).
[[nodiscard]] inline bool Valid(const Params& p) {
	return p.n != 0 && p.n <= 65536u && p.r != 0 && p.r <= 4096u && p.trailer <= 65536u &&
	       p.args != 0 && p.input != 0 && p.output != 0;
}

// The input: N index dwords, then N records of R bytes. The output region: 8 header bytes, N record
// slots, the trailer.
[[nodiscard]] inline uint64_t InputBytes(const Params& p) {
	return uint64_t {p.n} * 4u + uint64_t {p.n} * p.r;
}
[[nodiscard]] inline uint64_t OutputBytes(const Params& p) {
	return 8u + uint64_t {p.n} * p.r + p.trailer;
}

// Bytes of the args buffer the survivors' indices reach (3 dwords at offset + stride * index).
[[nodiscard]] inline uint64_t ArgsExtent(const Params& p, const uint8_t* input) {
	uint64_t extent = 0;
	for (uint32_t i = 0; i < p.n; i++) {
		uint32_t index = 0;
		std::memcpy(&index, input + i * 4u, 4);
		if (index != 0xffffffffu) {
			extent =
			    std::max(extent, uint64_t {p.args_offset} + uint64_t {p.args_stride} * index + 12u);
		}
	}
	return extent;
}

// The compaction, in place on the output region (OutputBytes). Returns the survivor count k.
inline uint32_t Compact(const Params& p, const uint8_t* input, const uint8_t* args,
                        uint8_t* output) {
	const uint8_t*       records = input + uint64_t {p.n} * 4u;
	uint32_t             k       = 0;
	std::vector<uint8_t> trailer(output + 8u + uint64_t {p.n} * p.r,
	                             output + 8u + uint64_t {p.n} * p.r + p.trailer);
	for (uint32_t i = 0; i < p.n; i++) {
		uint32_t index = 0;
		std::memcpy(&index, input + i * 4u, 4);
		if (index == 0xffffffffu) {
			continue;
		}
		uint32_t xyz[3] {};
		std::memcpy(xyz, args + p.args_offset + uint64_t {p.args_stride} * index, 12);
		if (xyz[0] == 0u || xyz[1] == 0u || xyz[2] == 0u) { // x*y*z == 0
			continue;
		}
		std::memcpy(output + 8u + uint64_t {k} * p.r, records + uint64_t {p.r} * i, p.r);
		k++;
	}
	std::memcpy(output + 8u + uint64_t {k} * p.r, trailer.data(), trailer.size());
	const uint32_t total = k * p.r;
	const uint32_t waves = (p.n + 63u) / 64u;
	std::memcpy(output, &total, 4);
	std::memcpy(output + 4, &waves, 4);
	return k;
}

